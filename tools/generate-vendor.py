#!/usr/bin/env python3
"""Regenerate Oreo makefiles from the reviewed source/destination mapping."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'vendor/samsung/ancora'
if not VENDOR.is_dir():
    VENDOR = ROOT  # Standalone vendor repository checkout.
entries = json.loads((ROOT / 'tools/vendor-files.json').read_text())
mk = ['# Generated by tools/generate-vendor.py; ARM32 blobs are unchanged.',
      'LOCAL_PATH := $(call my-dir)', 'ifeq ($(TARGET_DEVICE),ancora)']
packages, copies = [], []
for e in entries:
    if not e['install']:
        continue
    if not (VENDOR / e['source']).is_file():
        raise SystemExit('Missing blob: ' + e['source'])
    if e['kind'] in ('library', 'executable'):
        packages.append(e['module'])
        destination = Path(e['destination'])
        mk += ['', 'include $(CLEAR_VARS)',
               'LOCAL_MODULE := ' + e['module'],
               'LOCAL_MODULE_STEM := ' + destination.name,
               'LOCAL_SRC_FILES := ' + e['source'],
               'LOCAL_MODULE_CLASS := ' + ('SHARED_LIBRARIES' if e['kind'] == 'library' else 'EXECUTABLES'),
               'LOCAL_MODULE_SUFFIX := ' + ('.so' if e['kind'] == 'library' else ''), 'LOCAL_MULTILIB := 32',
               'LOCAL_MODULE_TAGS := optional',
               'LOCAL_MODULE_PATH := $(PRODUCT_OUT)/' + str(destination.parent),
               'LOCAL_STRIP_MODULE := false', 'include $(BUILD_PREBUILT)']
    else:
        copies.append('vendor/samsung/ancora/' + e['source'] + ':' + e['destination'])
mk += ['', 'endif', '']
(VENDOR / 'Android.mk').write_text('\n'.join(line.rstrip() for line in mk))
product = '# Generated by tools/generate-vendor.py.\n'
for variable, values in [('PRODUCT_PACKAGES', packages), ('PRODUCT_COPY_FILES', copies)]:
    product += variable + ' += \\\n    ' + ' \\\n    '.join(values) + '\n\n'
(VENDOR / 'device-vendor-blobs.mk').write_text(product.rstrip() + '\n')
print(f'Generated {len(packages)} prebuilt modules and {len(copies)} copy entries.')
